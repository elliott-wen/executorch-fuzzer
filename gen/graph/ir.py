"""graph_ir.py — the computation-graph data structure (GenGraph).

A functional DAG: each node is (op, slots) where `op` is an OpNode (a real aten
op) or an AdapterNode (inserted cast/broadcast glue), and `slots` is the FULL
arg list in named_params order — each ('leaf', i) | ('ref', nid) | ('const', v).

This module is pure GENERATION: it builds the DAG and renders a graph-DEFINITION
script (`emit`). It does NOT execute graphs — that's execute/runner.py.
"""

from __future__ import annotations

from typing import Any

import torch

from mobile.gen.graph.emit import _qualname, _const_repr

# Single-op DOMAIN fuzzing: per-float-leaf probability of injecting a boundary value
# (NaN / ±inf / ±0) into a subset of its elements. Leaves otherwise come from torch.randn
# (always finite), so a single-op graph would never feed the op a non-finite input and would
# miss bugs gated on one (clamp/min/max/relu/hardtanh NaN-launder, exp(NaN), rsqrt(±0)). Kept
# low so it barely dents yield but every op still sees the boundary domain across the corpus.
NONFINITE_PROB = 0.0005


class GenGraph:
    def __init__(self):
        self.leaves: list[torch.Tensor] = []
        self.nodes: list[tuple[Any, list]] = []  # (op, slots)

    def add(self, op, input_slots: list) -> int:
        slots = []
        for kind, val in input_slots:
            if kind == "leaf":
                self.leaves.append(val)
                slots.append(("leaf", len(self.leaves) - 1))
            else:  # ('ref', nid) | ('const', value)
                slots.append((kind, val))
        self.nodes.append((op, slots))
        return len(self.nodes) - 1

    def sink_ids(self) -> list[int]:
        """Node ids not consumed by any other node — the graph's outputs."""
        consumed = {v for _, slots in self.nodes for k, v in slots if k == "ref"}
        return [nid for nid in range(len(self.nodes)) if nid not in consumed]

    def describe(self) -> str:
        sinks = set(self.sink_ids())
        out = []
        for nid, (op, slots) in enumerate(self.nodes):
            ins = ",".join((f"L{v}" if k == "leaf" else f"n{v}" if k == "ref"
                            else "·") for k, v in slots)
            out.append(f"n{nid}{'*' if nid in sinks else ''}={op.label}({ins})")
        return " ; ".join(out)

    def emit(self, seed: int = 0, nonfinite_prob: float = NONFINITE_PROB) -> str | None:
        """Render this DAG as a graph-DEFINITION script (defines g / LEAVES;
        no execution code). Returns None if a baked argument can't be
        emitted as source.

        `nonfinite_prob` (default `NONFINITE_PROB` = 0.01) turns on DOMAIN fuzzing:
        each float leaf has this probability of having a subset of its elfvp_clientements
        replaced by a boundary value (NaN / ±inf / ±0). Set 0.0 for the finite-only
        emitter. This exposes bugs gated on a non-finite *input*
        (clamp/min/max/relu/hardtanh NaN-launder, exp(NaN), rsqrt(±0)) that a
        single-op graph otherwise never feeds the op, because its leaves come from
        torch.randn (always finite). The injection is driven by the same seeded RNG,
        so eager reference and device get byte-identical inputs."""
        lines = []
        w = lines.append
        w('"""Auto-generated by mobile — graph definition.')
        w(f"Graph: {self.describe()}")
        w("Run via the mobile ExecuTorch fuzzer (xnnpack_client / ...).")
        w('"""')
        w("import torch")
        w(f"torch.manual_seed({seed})  # reproducible leaf data")
        w("")
        w("def _make(shape, dtype):")
        w("    if dtype.is_floating_point or dtype.is_complex:")
        w("        return torch.randn(shape, dtype=dtype)")
        w("    if dtype == torch.bool:")
        w("        return torch.randint(0, 2, shape, dtype=dtype)")
        w("    lo = -4 if dtype.is_signed else 0  # unsigned dtypes reject a negative low")
        w("    return torch.randint(lo, 5, shape, dtype=dtype)")
        w("")
        inject = nonfinite_prob and nonfinite_prob > 0.0
        if inject:
            w(f"_NONFIN_P = {float(nonfinite_prob)!r}  # single-op domain-fuzz probability")
            w("def _inject(t):")
            w("    # exercise non-finite / boundary INPUT domains (NaN/inf/-inf/0/-0).")
            w("    if not t.dtype.is_floating_point or t.numel() == 0:")
            w("        return t  # nan/inf only meaningful for real floats")
            w("    if torch.rand(1).item() >= _NONFIN_P:")
            w("        return t  # leave this leaf clean")
            w("    choices = [float('nan'), float('inf'), float('-inf'), 0.0, -0.0]")
            w("    v = choices[int(torch.randint(len(choices), (1,)).item())]")
            w("    mask = torch.rand(t.shape) < 0.5")
            w("    mask.reshape(-1)[0] = True  # guarantee >=1 injected element")
            w("    return torch.where(mask, torch.full_like(t, v), t)")
            w("")
        w("def _first(r):")
        w("    if isinstance(r, torch.Tensor): return r")
        w("    if isinstance(r, (tuple, list)):")
        w("        for x in r:")
        w("            if isinstance(x, torch.Tensor): return x")
        w("    return r")
        w("")
        for i, t in enumerate(self.leaves):
            mk = f"_make({tuple(t.shape)}, {t.dtype})"
            w(f"L{i} = _inject({mk})" if inject else f"L{i} = {mk}")
        leaf_args = ", ".join(f"L{i}" for i in range(len(self.leaves)))
        w("")
        w(f"def g({leaf_args}):")
        for nid, (op, slots) in enumerate(self.nodes):
            # Per-arg source exprs aligned to named_params, then split into
            # pos/kwargs by the op's schema (kwarg-only args like out= must be kw).
            exprs = []
            for k, v in slots:
                if k == "leaf":
                    exprs.append(f"L{v}")
                elif k == "ref":
                    exprs.append(f"n{v}")
                else:
                    r = _const_repr(v)
                    if r is None:
                        return None  # un-emittable arg → skip this graph
                    exprs.append(r)
            try:
                sched = op.op._schema.arguments
            except Exception:
                return None
            pos, kw = [], []
            for idx, (_pname, _pt) in enumerate(op.named_params):
                if idx >= len(exprs) or idx >= len(sched):
                    break
                sa = sched[idx]
                if getattr(sa, "kwarg_only", False):
                    kw.append(f"{sa.name}={exprs[idx]}")
                else:
                    pos.append(exprs[idx])
            call = f"{_qualname(op.op_name)}({', '.join(pos + kw)})"
            w(f"    n{nid} = _first({call})")
        sinks = self.sink_ids()
        w(f"    return ({', '.join(f'n{s}' for s in sinks)},)")
        w("")
        w(f"LEAVES = [{leaf_args}]")
        return "\n".join(lines)
